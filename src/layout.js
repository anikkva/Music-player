// Where the radio sits in the cabin.
//
// Not in the dash face where the factory radio sits, but hung just under it
// and closer to the driver, the way an aftermarket cassette deck was fitted to
// a car built before anyone sold one.
//
// The reason is reach. Flush in the dash it sat 0.85 m from the driver's
// shoulder and his arm is 0.6 m; touching it meant bending his spine or
// rolling his shoulder, and with the camera sitting twenty centimetres from
// that shoulder both put his own body across the shot. Mounted where a hand
// falls, the arm goes out and presses it on its own, and nothing crosses the
// view. The angle still comes from rays cast at the dash panel behind it.
//
// The scale is not vanity. The faceplate was modelled 37 cm wide so it would
// read at the framing distance; the panel it now lives on is about 16 cm of
// flat, so the unit is taken down to roughly period size and the camera's
// close zoom does the rest.

// Out from behind the wheel, and nearer for it. At the old spot the rim and
// the near spoke crossed the left third of the faceplate — AM, FM, BAND and
// the VOL knob all sat behind steel from the driver's seat. Sliding it right
// clears the rim; pulling it back toward the driver keeps his shoulder-to-unit
// distance from growing while it moves, so the reach is no worse than before.
export const RADIO_POSITION = [0.40, -0.35, -0.56];
export const RADIO_YAW = 0.02;
export const RADIO_PITCH = -0.20;
export const RADIO_SCALE = 0.72;
